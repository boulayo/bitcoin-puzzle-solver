"""Turns a design file of tools/research/ksim.c (first line the modulus, then "coefficient residue start end share" with the zone in
units of W) into the table of species of src/kangaroo.c: zone in thousandths of W, share in millionths of the herd.

    python3 -I tools/research/kspec_table.py tools/research/kang_schema3.txt > src/kang_spec3.inc
"""
import sys
rows = [l.split() for l in open(sys.argv[1]) if l.strip()]
M = int(rows[0][0])
assert M == 12, "the program uses residues mod 12 (KANG_MOD)"
sp = [(int(c), int(r), float(lo), float(hi), float(w)) for c, r, lo, hi, w in rows[1:]]
tot = sum(s[4] for s in sp)
out = []
for c, r, lo, hi, w in sp:
    l, h = round(lo * 1000), round(hi * 1000)
    assert abs(l - lo * 1000) < 1e-6 and abs(h - hi * 1000) < 1e-6, "zone edges must be whole thousandths of W"
    out.append((c, r, l, h, max(1, round(w / tot * 1e6))))
print("/* generated by tools/research/kspec_table.py from %s: {coefficient, residue mod 12, start, end (thousandths of W), share (millionths)} */" % sys.argv[1].split('/')[-1])
for i in range(0, len(out), 4):
    print("    " + " ".join("{%d, %d, %d, %d, %d}," % o for o in out[i:i + 4]))
